-- Persistent in-app notifications + standards-based Web Push.
--
-- IMPORTANT: VAPID private material is intentionally NOT source-controlled.
-- Provision these three secret names in Supabase Vault before enabling Web Push:
--   tournal_vapid_public_key
--   tournal_vapid_private_key
--   tournal_push_dispatch_secret
-- The production project already has them provisioned.

create table if not exists public.notifications (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  boutique_id text references public.boutiques(id) on delete cascade,
  category text not null default 'general',
  title text not null,
  body text not null default '',
  icon text not null default '🔔',
  action_tab text,
  action_filter jsonb,
  source_audit_id bigint references public.audit_log(id) on delete set null,
  created_at timestamptz not null default now(),
  read_at timestamptz,
  dismissed_at timestamptz,
  push_dispatched_at timestamptz,
  constraint notifications_category_check check (category in ('sale','payment','refund','stock','transfer','charge','client','supplier','security','caisse','general')),
  constraint notifications_source_user_unique unique (source_audit_id,user_id)
);
create index if not exists notifications_user_created_idx on public.notifications(user_id,created_at desc);
create index if not exists notifications_user_unread_idx on public.notifications(user_id,created_at desc) where read_at is null and dismissed_at is null;
alter table public.notifications enable row level security;
revoke all on public.notifications from public,anon;
grant select on public.notifications to authenticated;
drop policy if exists "notifications: own select" on public.notifications;
create policy "notifications: own select" on public.notifications for select to authenticated using (user_id=auth.uid());

create table if not exists public.push_subscriptions (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  endpoint text not null unique,
  p256dh text not null,
  auth text not null,
  user_agent text,
  device_label text,
  enabled boolean not null default true,
  created_at timestamptz not null default now(),
  last_seen_at timestamptz not null default now(),
  constraint push_subscriptions_endpoint_len check (length(endpoint) between 20 and 4096),
  constraint push_subscriptions_p256dh_len check (length(p256dh) between 20 and 512),
  constraint push_subscriptions_auth_len check (length(auth) between 8 and 256)
);
create index if not exists push_subscriptions_user_idx on public.push_subscriptions(user_id,enabled);
alter table public.push_subscriptions enable row level security;
revoke all on public.push_subscriptions from public,anon,authenticated;
grant select on public.push_subscriptions to authenticated;
drop policy if exists "push subscriptions: own select" on public.push_subscriptions;
create policy "push subscriptions: own select" on public.push_subscriptions for select to authenticated using (user_id=auth.uid());

create or replace function private.notification_category(p_action text)
returns text language sql immutable set search_path='' as $$
  select case
    when coalesce(p_action,'') ~* 'permission|rôle|role|compte|auth' then 'security'
    when coalesce(p_action,'') ~* 'caisse' then 'caisse'
    when coalesce(p_action,'') ~* 'retour|rembours' then 'refund'
    when coalesce(p_action,'') ~* 'encaissement|solde|versement|paiement' then 'payment'
    when coalesce(p_action,'') ~* 'transfert|partenaire' then 'transfer'
    when coalesce(p_action,'') ~* 'charge' then 'charge'
    when coalesce(p_action,'') ~* 'client' then 'client'
    when coalesce(p_action,'') ~* 'fournisseur' then 'supplier'
    when coalesce(p_action,'') ~* 'stock|produit|catégorie|categorie|inventaire' then 'stock'
    when coalesce(p_action,'') ~* 'commande|vente|facture' then 'sale'
    else 'general' end;
$$;
revoke all on function private.notification_category(text) from public,anon,authenticated;

create or replace function private.notification_tab(p_category text)
returns text language sql immutable set search_path='' as $$
  select case p_category
    when 'sale' then 'factures'
    when 'payment' then 'factures'
    when 'refund' then 'factures'
    when 'stock' then 'stock'
    when 'transfer' then 'transferts'
    when 'charge' then 'charges'
    when 'client' then 'clients'
    when 'supplier' then 'fournisseurs'
    when 'caisse' then 'dashboard'
    when 'security' then 'admin'
    else 'dashboard' end;
$$;
revoke all on function private.notification_tab(text) from public,anon,authenticated;

create or replace function private.emit_audit_notification()
returns trigger language plpgsql security definer set search_path='' as $$
declare v_category text;
begin
  v_category:=private.notification_category(new.action);
  insert into public.notifications(user_id,boutique_id,category,title,body,icon,action_tab,source_audit_id)
  select distinct a.user_id,new.boutique_id,v_category,new.action,coalesce(new.detail,''),coalesce(nullif(new.icon,''),'🔔'),private.notification_tab(v_category),new.id
  from public.boutique_assignments a
  join public.platform_users u on u.id=a.user_id and not coalesce(u.is_suspended,false)
  where a.boutique_id=new.boutique_id
    and (
      a.role='owner'
      or v_category='general'
      or (v_category='sale' and (coalesce((a.droits->>'factures')::boolean,false) or coalesce((a.droits->>'vente')::boolean,false)))
      or (v_category='payment' and (coalesce((a.droits->>'factures')::boolean,false) or coalesce((a.droits->>'encaissement_vente')::boolean,false)))
      or (v_category='refund' and (coalesce((a.droits->>'factures')::boolean,false) or coalesce((a.droits->>'remboursement')::boolean,false)))
      or (v_category in ('stock','transfer') and (coalesce((a.droits->>'stock')::boolean,false) or coalesce((a.droits->>'inventaire')::boolean,false)))
      or (v_category='charge' and coalesce((a.droits->>'charges')::boolean,false))
      or (v_category='client' and coalesce((a.droits->>'clients')::boolean,false))
      or (v_category='supplier' and coalesce((a.droits->>'fournisseurs')::boolean,false))
      or (v_category='caisse' and (coalesce((a.droits->>'vente')::boolean,false) or coalesce((a.droits->>'encaissement_vente')::boolean,false)))
    )
  on conflict (source_audit_id,user_id) do nothing;

  if v_category='security' then
    insert into public.notifications(user_id,boutique_id,category,title,body,icon,action_tab,source_audit_id)
    select u.id,new.boutique_id,v_category,new.action,coalesce(new.detail,''),coalesce(nullif(new.icon,''),'🛡️'),'admin',new.id
    from public.platform_users u
    where u.is_super_admin=true and not coalesce(u.is_suspended,false)
    on conflict (source_audit_id,user_id) do nothing;
  end if;
  return new;
end;
$$;
revoke all on function private.emit_audit_notification() from public,anon,authenticated;
drop trigger if exists audit_log_emit_notification on public.audit_log;
create trigger audit_log_emit_notification after insert on public.audit_log for each row execute function private.emit_audit_notification();

create or replace function private.emit_low_stock_notification()
returns trigger language plpgsql security definer set search_path='' as $$
begin
  if new.low_stock_threshold is not null
     and new.low_stock_threshold>0
     and new.stock<=new.low_stock_threshold
     and (old.stock>old.low_stock_threshold or old.low_stock_threshold is null or old.low_stock_threshold<=0) then
    insert into public.notifications(user_id,boutique_id,category,title,body,icon,action_tab)
    select distinct a.user_id,new.boutique_id,'stock','Stock faible',new.nom||' : '||new.stock||' '||coalesce(new.unit,''),'⚠️','stock'
    from public.boutique_assignments a
    join public.platform_users u on u.id=a.user_id and not coalesce(u.is_suspended,false)
    where a.boutique_id=new.boutique_id
      and (a.role='owner' or coalesce((a.droits->>'stock')::boolean,false) or coalesce((a.droits->>'inventaire')::boolean,false));
  end if;
  return new;
end;
$$;
revoke all on function private.emit_low_stock_notification() from public,anon,authenticated;
drop trigger if exists products_low_stock_notification on public.products;
create trigger products_low_stock_notification after update of stock,low_stock_threshold on public.products for each row execute function private.emit_low_stock_notification();

