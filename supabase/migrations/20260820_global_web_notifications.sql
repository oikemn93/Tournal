create or replace function private.dispatch_notification_push()
returns trigger language plpgsql security definer set search_path='' as $$
declare v_secret text;
begin
  if not exists(select 1 from public.push_subscriptions s where s.user_id=new.user_id and s.enabled=true) then return new; end if;
  select secret into v_secret from vault.decrypted_secrets where name='tournal_push_dispatch_secret' limit 1;
  if v_secret is null then return new; end if;
  begin
    perform net.http_post(
      url:='https://cnxtylngddwmhugxkzju.supabase.co/functions/v1/web-push-dispatch',
      headers:=jsonb_build_object('Content-Type','application/json','x-tournal-push-secret',v_secret),
      body:=jsonb_build_object('notificationId',new.id),
      timeout_milliseconds:=5000
    );
  exception when others then null;
  end;
  return new;
end;
$$;
revoke all on function private.dispatch_notification_push() from public,anon,authenticated;
drop trigger if exists notifications_dispatch_web_push on public.notifications;
create trigger notifications_dispatch_web_push after insert on public.notifications for each row execute function private.dispatch_notification_push();

create or replace function public.claim_push_subscription(
  p_endpoint text,p_p256dh text,p_auth text,p_user_agent text default null,p_device_label text default null
)
returns uuid language plpgsql security definer set search_path='' as $$
declare v_uid uuid:=auth.uid(); v_id uuid;
begin
  if v_uid is null then raise exception 'Connexion requise'; end if;
  if not exists(select 1 from public.platform_users u where u.id=v_uid and not coalesce(u.is_suspended,false)) then raise exception 'Compte inactif'; end if;
  if p_endpoint is null or length(p_endpoint)<20 or length(p_endpoint)>4096 then raise exception 'Abonnement Push invalide'; end if;
  if p_p256dh is null or length(p_p256dh)<20 or p_auth is null or length(p_auth)<8 then raise exception 'Clés Push invalides'; end if;
  insert into public.push_subscriptions(user_id,endpoint,p256dh,auth,user_agent,device_label,enabled,last_seen_at)
  values(v_uid,p_endpoint,p_p256dh,p_auth,left(p_user_agent,1000),left(p_device_label,200),true,now())
  on conflict(endpoint) do update set user_id=excluded.user_id,p256dh=excluded.p256dh,auth=excluded.auth,user_agent=excluded.user_agent,device_label=excluded.device_label,enabled=true,last_seen_at=now()
  returning id into v_id;
  return v_id;
end;
$$;
revoke all on function public.claim_push_subscription(text,text,text,text,text) from public,anon;
grant execute on function public.claim_push_subscription(text,text,text,text,text) to authenticated;

create or replace function public.remove_push_subscription(p_endpoint text)
returns void language plpgsql security definer set search_path='' as $$
begin
  if auth.uid() is null then raise exception 'Connexion requise'; end if;
  delete from public.push_subscriptions where endpoint=p_endpoint and user_id=auth.uid();
end;
$$;
revoke all on function public.remove_push_subscription(text) from public,anon;
grant execute on function public.remove_push_subscription(text) to authenticated;

