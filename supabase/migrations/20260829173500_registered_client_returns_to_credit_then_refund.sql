  if v_refund_method not in ('Espèces','Wave','Orange Money','Autre') then raise exception 'invalid refund payment method'; end if;$old$;
    v_new := $new$  if v_original.client_id is null then
    v_refund_method := coalesce(nullif(btrim(p_refund_method),''), nullif(btrim(v_original.payment_method),''), 'Autre');
