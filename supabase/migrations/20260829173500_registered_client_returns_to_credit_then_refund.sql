  else
    -- registered client: keep paid value as client credit; refund only via refund_client_advance.
    v_refund_method := null;
  end if;$new$;
    if v_def=replace(v_def,v_old,v_new) then raise exception 'return_sale refund-method patch marker not found'; end if;
    v_def:=replace(v_def,v_old,v_new);
    v_old := $old$  v_remaining_unpaid := greatest(0,v_original.montant-v_paid_total-v_prior_receivable);
