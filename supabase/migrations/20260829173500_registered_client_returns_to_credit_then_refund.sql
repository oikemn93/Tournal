-- Registered-client returns: keep paid value as client credit first.
-- Counter sales continue to refund immediately. A registered client's credit can
-- later be refunded explicitly and is consumed FIFO with an immutable refund ledger.

create table if not exists public.client_advance_refunds (
  id bigint generated by default as identity primary key,
  boutique_id text not null references public.boutiques(id) on delete restrict,
  client_id bigint not null,
  amount numeric(12,2) not null check (amount > 0),
  payment_method text not null check (payment_method in ('Espèces','Wave','Orange Money','Autre')),
  refunded_at timestamptz not null default now(),
  operator_id uuid not null,
  operator_name text not null,
  idempotency_key uuid not null,
  allocations jsonb not null default '[]'::jsonb,
  note text,
  unique (boutique_id,idempotency_key),
  foreign key (boutique_id,client_id) references public.clients(boutique_id,id) on delete restrict
);
alter table public.client_advance_refunds enable row level security;
revoke all on public.client_advance_refunds from anon, authenticated;
grant select on public.client_advance_refunds to authenticated;
drop policy if exists client_advance_refunds_select on public.client_advance_refunds;
create policy client_advance_refunds_select on public.client_advance_refunds for select to authenticated using (private.auth_has_boutique_access(boutique_id));
create index if not exists client_advance_refunds_client_idx on public.client_advance_refunds(boutique_id,client_id,refunded_at desc,id desc);

