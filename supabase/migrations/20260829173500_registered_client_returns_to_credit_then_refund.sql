  if v_remaining_value>v_epsilon then raise exception 'return amount exceeds remaining financial basis'; end if;$old$;
    v_new := $new$  v_remaining_unpaid := greatest(0,v_original.montant-v_paid_total-v_prior_receivable);
  v_remaining_value := v_total;
  v_receivable_reduction := least(v_remaining_value,v_remaining_unpaid);
  v_remaining_value := round(v_remaining_value-v_receivable_reduction,2);
  if v_original.client_id is not null then
    v_remaining_external := greatest(0,v_paid_total-v_prior_credit-v_prior_refund);
    v_credit_restore := least(v_remaining_value,v_remaining_external);
    v_remaining_value := round(v_remaining_value-v_credit_restore,2);
    v_refund_amount := 0;
  else
    v_remaining_advance := greatest(0,v_advance_paid-v_prior_credit);
    v_remaining_external := greatest(0,v_external_paid-v_prior_refund);
    v_credit_restore := least(v_remaining_value,v_remaining_advance);
    v_remaining_value := round(v_remaining_value-v_credit_restore,2);
    v_refund_amount := least(v_remaining_value,v_remaining_external);
    v_remaining_value := round(v_remaining_value-v_refund_amount,2);
  end if;
  if v_remaining_value>v_epsilon then raise exception 'return amount exceeds remaining financial basis'; end if;$new$;
