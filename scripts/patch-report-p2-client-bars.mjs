import fs from "node:fs";
const path = "src/app/screens/RapportViewV2.tsx";
let s = fs.readFileSync(path, "utf8");
const oldMax = 'const max=Math.max(1,...rows.slice(0,5).map(r=>r.invoiced_revenue));';
const newMax = 'const max=Math.max(1,...rows.slice(0,5).map(r=>Math.abs(r.invoiced_revenue)));';
const oldWidth = '${Math.max(2,x.value/max*100)}%';
const newWidth = '${Math.max(2,Math.abs(x.value)/max*100)}%';
if (!s.includes(oldMax)) throw new Error("P2 client max anchor missing");
if (!s.includes(oldWidth)) throw new Error("P2 client bar anchor missing");
s = s.replace(oldMax, newMax).replace(oldWidth, newWidth);
fs.writeFileSync(path, s);
